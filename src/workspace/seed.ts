// `.texdesk/plugins/`): the API declarations, a tsconfig for editor autocomplete, a README.

import typesSource from "../snippets/types.ts?raw";

const DECLARATIONS = `
  export function s(trigger: string | RegExp, replacement: Replacement, options?: SnippetOptions): Snippet;
  export function key(key: string, run: (ctx: Context) => SnippetResult): KeyHandler;
  export function key(key: string, options: KeyOptions, run: (ctx: Context) => SnippetResult): KeyHandler;
  /** Wrap a file's default export: \`export default snippets([...])\`. */
  export function snippets(list: readonly Snippet[]): Snippet[];
  /** Optional typing helper for a list of key handlers (a plain array works for the \`keys\` export). */
  export function keys(list: readonly KeyHandler[]): KeyHandler[];
`;

export function texdeskDts(): string {
  const body = typesSource
    .replace(/^(\/\/.*\n)+\n?/, "") // drop the file header comment
    .split("\n")
    .map((l) => (l ? "  " + l : l))
    .join("\n");
  return `// Generated by TeXdesk; rewritten on startup. Do not edit.\ndeclare module "texdesk" {\n${body.trimEnd()}\n${DECLARATIONS}}\n`;
}

